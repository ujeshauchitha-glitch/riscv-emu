//! The C (compressed) extension.
//!
//! The interesting half of this suite is a table of encodings produced by the **real GNU
//! assembler**, not by anything in this repository. Each row pairs a compressed
//! instruction with the 32-bit instruction the specification says it is equivalent to,
//! both assembled by `riscv64-unknown-elf-as`. If decompress() turns the first into the
//! second, the expansion is right - and it is right against an independent
//! implementation, which is the only kind of check worth having for a table of
//! hand-transcribed bit positions.
//!
//! The immediates deliberately include both extremes of each field's range. A bit placed
//! in the wrong position often still produces the right answer for small values, and only
//! diverges at the top of the range.

