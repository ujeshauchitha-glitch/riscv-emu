#[test]
fn expansions_match_the_assembler() {
    for &(compressed, expansion, c_asm, x_asm) in CASES {
        let got = decompress(compressed);
        assert_eq!(got, expansion, "{c_asm} -> got {got:#010x}, expected {expansion:#010x} ({x_asm})");
    }
}

#[test]
fn illegal_encodings_expand_to_zero() {
    // Zero is permanently illegal in RISC-V, deliberately, so that a jump into zeroed memory
    // faults at once rather than running through it. decompress() reuses that: an encoding
    // with no meaning expands to zero and the normal illegal-instruction path takes over.
    assert_eq!(decompress(0x0000), 0); // the all-zero halfword
    assert_eq!(decompress(0x0002), 0); // C.ADDI4SPN with nzuimm == 0
    assert_eq!(decompress(0x6001), 0); // C.LUI with rd == x0
    assert_eq!(decompress(0x6101), 0); // C.LUI with a zero immediate
    assert_eq!(decompress(0x2001), 0); // C.ADDIW with rd == x0
    assert_eq!(decompress(0x9c61), 0); // reserved MISC-ALU encoding
    assert_eq!(decompress(0x8002), 0); // C.JR with rs1 == x0
}

#[test]
fn double_precision_compressed_loads_and_stores() {
    // C.FLD / C.FSD / C.FLDSP / C.FSDSP move eight bytes, so they share their immediate
    // layout with C.LD / C.SD / C.LDSP / C.SDSP - only the opcode of the expansion differs.
    assert_eq!(decompress(0x2188), 0x0005b507); // c.fld  fa0, 0(a1)
    assert_eq!(decompress(0xa188), 0x00a5b027); // c.fsd  fa0, 0(a1)
    assert_eq!(decompress(0x2502), 0x00013507); // c.fldsp fa0, 0(sp)
    assert_eq!(decompress(0xa02a), 0x00a13027); // c.fsdsp fa0, 0(sp)

    // f0 is an ordinary register - nothing is hardwired to zero in the float file - so
    // `c.fldsp f0` is legal where `c.ldsp x0` is a reserved encoding.
    assert_ne!(decompress(0x2002), 0); // c.fldsp f0, 0(sp)
    assert_eq!(decompress(0x6002), 0); // c.ldsp  x0, 0(sp)  - reserved
}

#[test]
fn instruction_length_is_read_from_the_low_bits() {
    // RISC-V marks length in the low two bits: 11 means 32 bits or wider, anything else
    // means a 16-bit compressed instruction. This is what lets the two lengths be mixed
    // freely with no mode bit anywhere.
    assert!(!is_32bit_instruction(0x0028)); // c.addi4spn
    assert!(!is_32bit_instruction(0x4188)); // c.lw
    assert!(!is_32bit_instruction(0x0001)); // c.nop
    assert!(is_32bit_instruction(0x0513)); // low half of addi a0, sp, 8
    assert!(is_32bit_instruction(0xffff));
}

#[test]
fn decode16_reports_length_and_original_encoding() {
    // A compressed instruction decodes as its expansion, so every execute path sees one
    // uniform 32-bit encoding - but `encoded` and `length` remember what the program
    // actually contained. mtval and the tracer need that: reporting the expansion would
    // name an instruction that is not there.
    let c = decode16(0x0028, 0); // c.addi4spn a0, sp, 8
    assert_eq!(c.raw, 0x00810513);
    assert_eq!(c.encoded, 0x0028);
    assert_eq!(c.length, 2);
    assert_eq!(c.opcode, opcodes::OP_IMM);
    assert_eq!(c.rd, 10);
    assert_eq!(c.imm, 8);

    let full = decode16(0x0513, 0x0081); // addi a0, sp, 8
    assert_eq!(full.raw, 0x00810513);
    assert_eq!(full.encoded, 0x00810513);
    assert_eq!(full.length, 4);
}

// --- executing compressed code ----------------------------------------------

/// Lay out a program of raw halfwords in DRAM. The Machine helper takes 32-bit words, so
/// mixed-width programs are assembled by hand here.
fn machine_from_halfwords(halves: &[u16]) -> Machine {
    let words: Vec<u32> = halves
        .chunks(2)
        .map(|c| (*c.get(1).unwrap_or(&0) as u32) << 16 | c[0] as u32)
        .collect();
    Machine::new(&words)
}

#[test]
fn compressed_program_executes_and_advances_two_bytes() {
    // c.li a0, 5 ; c.li a1, 7 ; c.add a0, a1
    let mut m = machine_from_halfwords(&[0x4515, 0x459d, 0x952e]);
    assert!(m.run(3).is_none());
    assert_eq!(m.reg(10), 12);
    // Three 2-byte instructions: the PC advanced by six, not twelve.
    assert_eq!(m.cpu.pc, DRAM_BASE + 6);
}

#[test]
fn compressed_and_full_width_instructions_interleave() {
    // c.li a0, 1 ; addi a0, a0, 10 (32-bit) ; c.addi a0, 1
    let a = addi(10, 10, 10);
    let mut m = machine_from_halfwords(&[0x4505, (a & 0xffff) as u16, (a >> 16) as u16, 0x0505]);
    assert!(m.run(3).is_none());
    assert_eq!(m.reg(10), 12);
    assert_eq!(m.cpu.pc, DRAM_BASE + 8); // 2 + 4 + 2
}

#[test]
fn compressed_branch_displacement() {
    //   c.li   a0, 0
    //   c.beqz a0, 2f     <- taken
    //   c.li   a0, 9      <- skipped
    // 2: c.li  a0, 21
    // Assembled by riscv64-unknown-elf-as, so the displacement is the real one rather than one
    // this repository computed for itself.
    let mut m = machine_from_halfwords(&[0x4501, 0xc111, 0x4525, 0x4555]);
    assert!(m.run(3).is_none());
    assert_eq!(m.reg(10), 21);
    // Two instructions ran and the branch skipped a third: 2 + 2 + 2.
    assert_eq!(m.cpu.pc, DRAM_BASE + 8);
}

#[test]
fn compressed_jump() {
    //   c.j   2f
    //   c.li  a1, 9       <- skipped
    // 2: c.li a1, 7
    let mut m = machine_from_halfwords(&[0xa011, 0x45a5, 0x459d]);
    assert!(m.run(2).is_none());
    assert_eq!(m.reg(11), 7);
    // C.J expands to `jal x0, offset`, so nothing was linked.
    assert_eq!(m.reg(1), 0);
}

#[test]
fn illegal_compressed_instruction_reports_its_own_bits() {
    // mtval must hold what was in memory - the 16-bit halfword - not the 32-bit expansion,
    // which for an illegal encoding does not exist anyway.
    let mut m = machine_from_halfwords(&[0x0000]);
    let t = m.cpu.step().unwrap_err();
    assert_eq!(t.cause, Exception::IllegalInstruction);
    assert_eq!(t.tval, 0);

    let mut m2 = machine_from_halfwords(&[0x6001]); // c.lui with rd = x0
    let t2 = m2.cpu.step().unwrap_err();
    assert_eq!(t2.cause, Exception::IllegalInstruction);
    assert_eq!(t2.tval, 0x6001);
}
